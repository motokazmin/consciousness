#!/usr/bin/env bash
# Запуск веб-инструмента.
#
#   ./start.sh            — как раньше
#   ./start.sh --accel    — сначала пересопрячь ремень, потом запусти
#
# Зачем --accel: на один bond H10 отдаёт акселерометр ровно в одном BLE-соединении
# (см. ARCHITECTURE.md § PMD-акселерометр). Значит одно пересопряжение = одна
# запись с акселерометром; на вторую запись понадобится ещё одно. Ремень должен
# быть надет.
set -u

if [ "${1:-}" = "--accel" ] || [ -n "${HRV_REPAIR:-}" ]; then
    if ! python -m hrv_core.ble_repair; then
        echo "Дальше без акселерометра: RR это не затрагивает." >&2
    fi
fi

python -m hrv_web
